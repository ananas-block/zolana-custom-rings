fn delivered_cases() -> Vec<Case> {
    let assets = [SOL, MINT, SOL, OTHER_MINT, SOL, MINT, SOL];
    let rings = |count: u8| {
        (0..count)
            .map(move |k| ring_output(0xb0 + k, assets[usize::from(k)], 100 * (u64::from(k) + 1)))
    };
    let dense: Vec<Output> = rings(7).chain([Output::Dummy]).collect();
    let exits: Vec<Output> = rings(6)
        .chain([Output::Exit(ring_utxo(0xe6, OTHER_MINT, 40)), Output::Dummy])
        .collect();
    let pair_exits: Vec<Output> = rings(1)
        .chain([Output::Exit(ring_utxo(0xe5, MINT, 40))])
        .collect();
    let quad_escrow: Vec<Output> = rings(3).chain([Output::Dummy]).collect();
    let in_proof = spent_utxo().commitment(spent_placement());
    [
        ("dense", &dense, false, None),
        ("exits", &exits, false, None),
        ("escrow", &dense, true, None),
        ("exits_escrow", &exits, true, None),
        ("pair_exits", &pair_exits, false, None),
        ("quad_escrow", &quad_escrow, true, None),
        ("in_proof", &pair_exits, false, Some(in_proof)),
    ]
    .into_iter()
    .map(|(name, outputs, key_escrow, input_hash)| {
        DeliveredCase {
            name,
            outputs,
            key_escrow,
            input_hash,
        }
        .case()
    })
    .collect()
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum AnonymousKey {
    /// Only ring notes, every input disclosed by its commitment.
    Commitment,
    /// A default-ring note among the spends, every input opens in full.
    Entry,
}

/// Spends of the sender paying two recipients, change under the sender tag, dummies past four outputs.
struct AnonymousCase {
    name: &'static str,
    key: AnonymousKey,
    exits: bool,
    inputs: usize,
    outputs: usize,
}

impl AnonymousCase {
    fn case(self) -> Case {
        let entry = self.key == AnonymousKey::Entry;
        let mut transfer = Transfer::fixture();
        transfer
            .nullifiers
            .extend((1..self.inputs).map(|index| field(0x1f - index as u8)));
        let sender_nullifier_pk = field(0x5a);
        let sender = |asset_address, amount| UtxoFields {
            owner_key: SENDER_KEY,
            nullifier_pk: sender_nullifier_pk,
            asset_address,
            amount,
            ..UtxoFields::default()
        };
        let change_tag = field(0x5c);
        let change = Output::Ring {
            utxo: sender(MINT, 500),
            recipient_u: [0; 32],
            tag: Some(change_tag),
        };
        let change_stream = json!({"stream": "change"});
        let payment = |owner, asset_address, amount, tag| {
            (
                Output::Ring {
                    utxo: ring_utxo(owner, asset_address, amount),
                    recipient_u: [0; 32],
                    tag: Some(field(tag)),
                },
                json!({"stream": "payment"}),
            )
        };
        let mut paid = vec![
            payment(0xb5, SOL, 4000, 0x31),
            payment(0xb6, MINT, 2500, 0x32),
        ];
        paid.extend(match self.exits {
            true => [
                (Output::Exit(ring_utxo(0xe7, SOL, 1000)), Value::Null),
                (change, change_stream),
            ],
            false => [(change, change_stream), (Output::Dummy, Value::Null)],
        });
        paid.resize_with(self.outputs, || (Output::Dummy, Value::Null));
        let (outputs, streams): (Vec<Output>, Vec<Value>) = paid.into_iter().unzip();
        let slots = transfer.slots(Rail::Anonymous, &outputs);
        let spent: Vec<_> = [(SOL, 5000), (MINT, 3000), (SOL, 1500)][..self.inputs]
            .iter()
            .enumerate()
            .map(|(index, (asset_address, amount))| {
                (
                    sender(*asset_address, *amount),
                    field(0x60 + index as u8),
                    (index == 0 || !entry).then_some(transfer.ring),
                )
            })
            .collect();
        let commitments: Vec<[u8; 32]> = spent
            .iter()
            .map(|(utxo, blinding, ring)| {
                utxo.commitment(Placement {
                    blinding: *blinding,
                    ring: *ring,
                    tree_id: transfer.tree_id,
                })
            })
            .collect();
        let inputs = match self.key {
            AnonymousKey::Entry => AuditEvidence::Entry {
                sender_key: SENDER_KEY,
                sender_nullifier_pk,
                inputs: spent
                    .iter()
                    .map(|(utxo, blinding, ring)| {
                        input_opening(
                            utxo,
                            Placement {
                                blinding: *blinding,
                                ring: *ring,
                                tree_id: transfer.tree_id,
                            },
                        )
                    })
                    .collect(),
            },
            AnonymousKey::Commitment => {
                input_hash_evidence(&commitments.iter().copied().map(Some).collect::<Vec<_>>())
                    .unwrap()
            }
        };
        let disclosure = transfer.anonymous_disclosure(&outputs, inputs);
        let class = disclosure.layout.key.class();
        let transaction = transfer.publish(Publish {
            slots: slots.iter().map(|slot| slot.output.clone()).collect(),
            disclosure: &disclosure,
            auditor: &auditor().pubkey(),
        });
        let layout = disclosure.layout;
        let frame = transfer.frame(Frame {
            tx: &transaction,
            disclosure: &disclosure,
        });
        let mut json = Map::new();
        json.insert("name".into(), self.name.into());
        json.insert(
            "layout".into(),
            layout_value(&frame, RingRail::Anonymous).into(),
        );
        json.extend(transfer_json(&transfer));
        json.insert("sender_key".into(), hex(SENDER_KEY).into());
        json.insert(
            "sender_nullifier_pk".into(),
            hex(sender_nullifier_pk).into(),
        );
        json.insert(
            "key".into(),
            match self.key {
                AnonymousKey::Entry => "entry",
                AnonymousKey::Commitment => "commitment",
            }
            .into(),
        );
        json.insert("class".into(), class.into());
        json.insert(
            "inputs".into(),
            spent
                .iter()
                .zip(&transfer.nullifiers)
                .zip(&commitments)
                .map(|(((utxo, blinding, ring), nullifier), commitment)| {
                    json!({
                        "nullifier": hex(nullifier),
                        "asset_address": hex(utxo.asset_address.as_array()),
                        "asset": hex(utxo.asset()),
                        "amount": utxo.amount,
                        "blinding": hex(blinding),
                        "input_tree_id": transfer.tree_id,
                        "ring": if ring.is_some() { "ring" } else { "default" },
                        "owner_hash": hex(utxo.owner_hash()),
                        "commitment": hex(commitment),
                    })
                })
                .collect(),
        );
        json.insert(
            "slots".into(),
            outputs
                .iter()
                .zip(&slots)
                .zip(streams)
                .map(|((output, slot), stream)| {
                    let mut map = slot_json(output, slot);
                    if let Value::Object(stream) = stream {
                        map.extend(stream);
                    }
                    Value::Object(map)
                })
                .collect(),
        );
        json.extend(stream_json(&transfer, &disclosure));
        let known = spent
            .iter()
            .zip(&commitments)
            .map(|((utxo, blinding, ring), commitment)| {
                let placement = Placement {
                    blinding: *blinding,
                    ring: *ring,
                    tree_id: transfer.tree_id,
                };
                (*commitment, known_utxo(utxo, placement))
            })
            .collect();
        let inputs = spent
            .iter()
            .zip(&transfer.nullifiers)
            .zip(&commitments)
            .map(|(((utxo, blinding, ring), nullifier), commitment)| {
                let commitment = *commitment;
                AuditedInput {
                    nullifier: *nullifier,
                    hash: commitment,
                    opening: InputOpening::Opened(AuditedInputOpening {
                        asset: utxo.asset(),
                        mint: Some(utxo.asset_address),
                        amount: utxo.amount,
                        blinding: *blinding,
                        ring: Some(match ring {
                            Some(_) => InputRing::Ring { commitment },
                            None => InputRing::Default { commitment },
                        }),
                    }),
                }
            })
            .collect();
        Case {
            json: Value::Object(json),
            audit: Audit {
                transaction,
                frame,
                mode: RingMode::Anonymous,
                layout,
                outputs: audited_outputs(&outputs, &slots),
                input_trees: vec![Some(transfer.tree_id); self.inputs],
                known,
                escrowed: HashMap::new(),
                inputs,
            },
        }
    }
}

fn anonymous_cases() -> Vec<Case> {
    [
        ("commitment", AnonymousKey::Commitment, false, 2, 4),
        ("commitment_exits", AnonymousKey::Commitment, true, 2, 4),
        ("commitment_pair", AnonymousKey::Commitment, false, 3, 4),
        ("entry", AnonymousKey::Entry, true, 2, 4),
    ]
    .into_iter()
    .map(|(name, key, exits, inputs, outputs)| {
        AnonymousCase {
            name,
            key,
            exits,
            inputs,
            outputs,
        }
        .case()
    })
    .collect()
}

fn file_json(description: &str, cases: &[Case]) -> Value {
    json!({
        "description": description,
        "cases": cases.iter().map(|case| case.json.clone()).collect::<Vec<_>>(),
    })
}

fn check_audit(audit: &Audit) {
    let origin = RingOrigin {
        ring_invoked: true,
        event: origin_fixture::event(&audit.transaction),
        signers: Vec::new(),
        pool_accounts: Vec::new(),
        withdrawals: Vec::new(),
        deposits: Vec::new(),
        merge_disclosure: None,
        transact: Some(audit.frame.clone()),
    };
    let layout = origin.audit_stream(audit.mode).unwrap();
    assert_eq!(layout, audit.layout);
    assert!(matches!(
        (layout.key, audit.mode),
        (AuditKey::Anonymous(_), RingMode::Anonymous)
            | (
                AuditKey::Confidential { .. },
                RingMode::Confidential | RingMode::ConfidentialEscrow
            )
    ));
    let opened = TransactionAudit::new(&audit.transaction, layout)
        .with_input_trees(&audit.input_trees)
        .unwrap()
        .with_known_utxos(&audit.known)
        .with_escrowed_keys(&audit.escrowed)
        .run(&auditor(), &assets())
        .unwrap();
    assert!(
        opened.payload_errors.is_empty(),
        "{:?}",
        opened.payload_errors
    );
    assert_eq!(opened.outputs, audit.outputs);
    assert_eq!(opened.inputs, audit.inputs);
}

fn check(cases: Vec<Case>, description: &str, committed: &str) {
    for case in &cases {
        check_audit(&case.audit);
    }
    assert_eq!(
        serde_json::from_str::<Value>(committed).unwrap(),
        file_json(description, &cases)
    );
}

