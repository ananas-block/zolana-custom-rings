const VECTOR: &str = include_str!("../../../test-vectors/audit/auditor-stream.json");

const DESCRIPTION: &str = "Worked ring streams, one per label and per record kind. head = Poseidon(right_align(label || 0x00), secret), tail = Poseidon(right_align(label || 0x01), secret), key = low31_be(head) || low13_be(tail)[0], nonce = low13_be(tail)[1..13], ct = AES-256-CTR(key, nonce || u32be(counter), plaintext). secret = Poseidon(CR_S, pack_be(X25519(eph_sk, auditor_u)), pack_be(0x04 || eph_u), pack_be(0x04 || auditor_u)) for the auditor stream, the register key and the deposit, and the CRDS slot secret for a delivered body. Envelope at counter 2, record of slot i at counter R0 + i * R with R0 = 4 + E_max(key). Generated by sdk-libs/keys/tests/stream_vectors.rs.";

const DEPOSIT_SLOT_BLOCKS: u32 = (RING_DEPOSIT_AUDIT_CIPHERTEXT_LEN / STREAM_BLOCK_LEN) as u32;

fn scalar(seed: u8) -> [u8; 32] {
    let mut out = core::array::from_fn(|i| seed ^ i as u8);
    out[0] = 0x01;
    out
}

fn field(byte: u8) -> [u8; 32] {
    let mut out = [byte; 32];
    out[0] = 0;
    out
}

struct Parties {
    eph: X25519Keypair,
    auditor: X25519Pubkey,
    secret: [u8; 32],
}

fn parties() -> Parties {
    let eph = X25519Keypair::from_bytes(&scalar(0x22));
    let auditor = X25519Keypair::from_bytes(&scalar(0x33)).pubkey();
    let [dh0, dh1] = pack_be(&eph.ecdh(&auditor).unwrap());
    let [eph0, eph1] = pack_be(eph.pubkey().as_bytes());
    let [aud0, aud1] = pack_be(auditor.as_bytes());
    let secret = Poseidon::hashv(&[
        &right_align(b"CR_S"),
        &dh0,
        &dh1,
        &eph0,
        &eph1,
        &aud0,
        &aud1,
    ])
    .unwrap();
    Parties {
        eph,
        auditor,
        secret,
    }
}

struct Worked<'a> {
    name: &'a str,
    label: &'a [u8; 10],
    secret: [u8; 32],
    counter: u32,
    plaintext: Vec<u8>,
}

impl Worked<'_> {
    /// The key and nonce come from the schedule's text, the ciphertext from the SDK stream.
    fn json(self) -> Value {
        let mut tag = [0u8; 11];
        tag[..10].copy_from_slice(self.label);
        let head = Poseidon::hashv(&[&right_align(&tag), &self.secret]).unwrap();
        tag[10] = 1;
        let tail = Poseidon::hashv(&[&right_align(&tag), &self.secret]).unwrap();
        let key = [&head[1..], &tail[19..20]].concat();
        let nonce = &tail[20..];
        let mut ciphertext = self.plaintext.clone();
        RingStream::new(&self.secret, self.label)
            .unwrap()
            .apply_at(self.counter, &mut ciphertext);
        let mut iv = [0u8; 16];
        iv[..12].copy_from_slice(nonce);
        iv[12..].copy_from_slice(&self.counter.to_be_bytes());
        let mut expected = self.plaintext.clone();
        let key_bytes: [u8; 32] = key.clone().try_into().unwrap();
        Ctr32BE::<Aes256>::new((&key_bytes).into(), (&iv).into()).apply_keystream(&mut expected);
        assert_eq!(ciphertext, expected, "{}", self.name);
        json!({
            "name": self.name,
            "label": String::from_utf8_lossy(self.label),
            "secret": hex::encode(self.secret),
            "head": hex::encode(head),
            "tail": hex::encode(tail),
            "key": hex::encode(key),
            "nonce": hex::encode(nonce),
            "counter": self.counter,
            "plaintext": hex::encode(&self.plaintext),
            "ciphertext": hex::encode(ciphertext),
        })
    }
}

fn be64(amount: u64) -> [u8; 8] {
    amount.to_be_bytes()
}

fn concat(parts: &[&[u8]]) -> Vec<u8> {
    parts.concat()
}

fn labels() -> Vec<Value> {
    let secret = parties().secret;
    let tx = ViewingKey::from_bytes(&scalar(0x11));
    let tx_viewing_sk = *tx.secret_bytes();
    let (input_0, input_1) = (field(0x60), field(0x61));
    let (sender_key, sender_nullifier_pk) = ([0xa1; 32], field(0x5a));
    let (asset, blinding) = (field(0x0a), field(0x40));
    let hashes = AuditEvidence::InputHashes(vec![input_0, input_1]);
    let envelope = |evidence| {
        AuditEnvelope {
            tx_viewing_secret: tx_viewing_sk,
            evidence,
        }
        .encode()
    };
    let auditor_stream = |name, plaintext| Worked {
        name,
        label: AUDIT_STREAM_LABEL,
        secret,
        counter: STREAM_FIRST_COUNTER,
        plaintext,
    };
    let recipient = X25519Keypair::from_bytes(&scalar(0x44)).pubkey();
    let first_nullifier = right_align(&[0x1f, 0x1f]);
    let salt: [u8; 16] = core::array::from_fn(|i| 0xa0 + i as u8);
    let slot_secret = *DeliveredSlot {
        agreement: &tx.ecdh(&recipient).unwrap(),
        tx_viewing_pk: tx.pubkey().as_bytes(),
        recipient_viewing_pk: recipient.as_bytes(),
        salt: &salt,
        output_index: 1,
        first_nullifier: &first_nullifier,
    }
    .secret()
    .unwrap()
    .as_bytes();
    let owner_key = [0xb0; 32];
    let nullifier_pk = field(0x20);
    let body = |name, plaintext| Worked {
        name,
        label: DELIVERED_BODY_LABEL,
        secret: slot_secret,
        counter: STREAM_FIRST_COUNTER,
        plaintext,
    };
    let deposit = |name, counter, seed: u8| Worked {
        name,
        label: DEPOSIT_AUDIT_LABEL,
        secret,
        counter,
        plaintext: concat(&[&field(seed), &field(seed + 1), &[seed + 2; 32]]),
    };
    [
        auditor_stream("envelope_signer", envelope(hashes.clone())),
        auditor_stream("envelope_in_proof_n2", envelope(hashes.clone())),
        auditor_stream("envelope_commitment_n2", envelope(hashes)),
        auditor_stream(
            "envelope_entry_n1",
            envelope(AuditEvidence::Entry {
                sender_key,
                sender_nullifier_pk,
                inputs: vec![EntryInput {
                    hash: input_0,
                    amount: 500,
                    asset,
                    blinding,
                }],
            }),
        ),
        body(
            "body_keyed",
            concat(&[&blinding, &be64(100), &owner_key, &nullifier_pk]),
        ),
        body(
            "body_key_escrow",
            concat(&[&blinding, &be64(100), &owner_key]),
        ),
        Worked {
            name: "register_key",
            label: REGISTER_KEY_LABEL,
            secret,
            counter: STREAM_FIRST_COUNTER,
            plaintext: right_align(&[0x07; 31]).to_vec(),
        },
        deposit("deposit_slot_0", STREAM_FIRST_COUNTER, 0x01),
        deposit(
            "deposit_slot_1",
            STREAM_FIRST_COUNTER + DEPOSIT_SLOT_BLOCKS,
            0x04,
        ),
    ]
    .into_iter()
    .map(Worked::json)
    .collect()
}

fn record_counter(key: AuditKey, slot: usize) -> u32 {
    AuditStreamLayout {
        key,
        key_escrow: false,
        inputs: 1,
        outputs: slot + 1,
        capacity: slot + 1,
        exits: 0,
    }
    .record(slot)
    .start_counter
}

fn records() -> Vec<Value> {
    let secret = parties().secret;
    let owner_key = [0xb0; 32];
    let (asset, nullifier_pk) = (field(0x0a), field(0x20));
    let anonymous = AuditKey::Anonymous(AnonymousAuditKey::Commitment { class: 4 });
    let confidential = AuditKey::Confidential { class: 2 };
    let record = |name, key, slot, plaintext| Worked {
        name,
        label: AUDIT_STREAM_LABEL,
        secret,
        counter: record_counter(key, slot),
        plaintext,
    };
    [
        record(
            "anonymous_ring_output_slot_1",
            anonymous,
            1,
            concat(&[&owner_key, &asset, &be64(4000), &nullifier_pk]),
        ),
        record("anonymous_dummy_slot_3", anonymous, 3, vec![0; 104]),
        record(
            "anonymous_exit_slot_2",
            anonymous,
            2,
            concat(&[&asset, &be64(1000), &nullifier_pk]),
        ),
        record(
            "confidential_exit_slot_1",
            confidential,
            1,
            concat(&[&asset, &be64(1000), &nullifier_pk]),
        ),
        record(
            "confidential_exit_key_escrow_slot_1",
            confidential,
            1,
            concat(&[&asset, &be64(1000)]),
        ),
    ]
    .into_iter()
    .map(Worked::json)
    .collect()
}

fn vector() -> Value {
    let Parties { eph, auditor, .. } = parties();
    json!({
        "description": DESCRIPTION,
        "eph_sk": hex::encode(*eph.secret_bytes()),
        "eph_u": hex::encode(eph.pubkey().u()),
        "auditor_u": hex::encode(auditor.u()),
        "labels": labels(),
        "records": records(),
    })
}

#[test]
fn stream_vectors_match() {
    assert_eq!(serde_json::from_str::<Value>(VECTOR).unwrap(), vector());
}

